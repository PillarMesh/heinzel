import {execFileSync} from "node:child_process"
import {mkdtempSync, readFileSync, rmSync, writeFileSync} from "node:fs"
import {tmpdir} from "node:os"
import {dirname, join, resolve} from "node:path"
import {fileURLToPath} from "node:url"

import Ajv2020 from "ajv/dist/2020.js"
import {_} from "ajv"
import standaloneCode from "ajv/dist/standalone/index.js"
import {compileFromFile} from "json-schema-to-typescript"

import {consoleFormats} from "../web/src/api/rfc3339-format.js"

const consoleRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const repositoryRoot = resolve(consoleRoot, "../..")
const committedSchema = join(consoleRoot, "schema/console-api-v1.json")
const committedTypes = join(consoleRoot, "web/src/api/generated.ts")
const checkOnly = process.argv.includes("--check")
const temporaryDirectory = mkdtempSync(join(tmpdir(), "heinzel-console-contracts-"))
const generatedSchema = checkOnly
  ? join(temporaryDirectory, "console-api-v1.json")
  : committedSchema
const generatedTypes = checkOnly ? join(temporaryDirectory, "generated.ts") : committedTypes
const committedValidators = join(consoleRoot, "web/src/api/generated-validators.js")
const generatedValidators = checkOnly
  ? join(temporaryDirectory, "generated-validators.js")
  : committedValidators
const schemaId = "https://pillarmesh.com/schemas/console-api-v1.json"

/**
 * Precompile the response validators to plain JavaScript.
 *
 * Ajv generates validator code at runtime with `new Function`, which the
 * console's own Content-Security-Policy forbids: the served bundle would throw
 * before React mounted. Compiling here keeps the validation the untrusted
 * network boundary needs without asking the policy to permit eval.
 */
function generateValidators(schemaPath, output) {
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"))
  const ajv = new Ajv2020({
    allErrors: true,
    code: {esm: true, formats: _`consoleFormats`, source: true},
    formats: consoleFormats,
    strict: true,
  })
  ajv.addSchema(schema, schemaId)
  const responseNames = Object.keys(schema.properties)
    .filter((name) => name.endsWith("_response"))
    .sort()
  for (const responseName of responseNames) {
    ajv.addSchema({$ref: `${schemaId}#/properties/${responseName}`}, responseName)
  }
  const exports = Object.fromEntries(responseNames.map((name) => [name, name]))
  const banner =
    "// Generated by scripts/generate-contracts.mjs. Do not edit.\n" +
    "//\n" +
    "// Precompiled so the bundle never calls new Function, which the console's\n" +
    "// Content-Security-Policy forbids.\n" +
    'import ucs2lengthModule from "ajv/dist/runtime/ucs2length.js"\n' +
    'import {consoleFormats} from "./rfc3339-format.js"\n\n' +
    "// The helper is CommonJS: a default import yields module.exports under Node\n" +
    "// and the function itself under some bundlers, so accept either shape.\n" +
    "const ucs2length = ucs2lengthModule.default ?? ucs2lengthModule\n\n"
  // Ajv still emits one CommonJS `require` for its ucs2length helper even with
  // `esm: true`, which makes the file unloadable as ESM outside a bundler. Hoist
  // it to a real import so the module stands on its own.
  const source = standaloneCode(ajv, exports).replaceAll(
    'require("ajv/dist/runtime/ucs2length").default',
    "ucs2length",
  )
  if (source.includes("require(")) {
    throw new Error("the generated validators still contain a CommonJS require")
  }
  writeFileSync(output, banner + source, "utf8")
}

function generateSchema(output) {
  execFileSync(
    "uv",
    ["run", "python", "-m", "heinzel_console.schema", "--output", output],
    {cwd: repositoryRoot, stdio: "inherit"},
  )
}

function assertMatches(generated, committed, label) {
  const generatedContent = readFileSync(generated, "utf8")
  const committedContent = readFileSync(committed, "utf8")
  if (generatedContent !== committedContent) {
    throw new Error(
      `${label} is stale; run npm run generate:contracts and commit the generated files`,
    )
  }
}

function preserveStrictEmptyObjects(types) {
  return types.replace(
    /^export interface ([A-Za-z_][A-Za-z0-9_]*) \{\}$/gm,
    "export type $1 = Record<string, never>",
  )
}

try {
  generateSchema(generatedSchema)
  const types = await compileFromFile(generatedSchema, {
    bannerComment: "",
    style: {
      bracketSpacing: false,
      printWidth: 100,
      semi: false,
      singleQuote: false,
      tabWidth: 2,
      trailingComma: "all",
      useTabs: false,
    },
    unknownAny: true,
  })
  writeFileSync(generatedTypes, preserveStrictEmptyObjects(types), "utf8")
  generateValidators(generatedSchema, generatedValidators)

  if (checkOnly) {
    assertMatches(generatedSchema, committedSchema, "console JSON Schema")
    assertMatches(generatedTypes, committedTypes, "generated TypeScript vocabulary")
    assertMatches(generatedValidators, committedValidators, "precompiled response validators")
  }
} finally {
  rmSync(temporaryDirectory, {force: true, recursive: true})
}
